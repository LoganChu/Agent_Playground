/**
 * Core types for the US federal tax engine.
 *
 * Design notes:
 * - All monetary values are plain `number` in whole dollars-and-cents (e.g. `1234.56`).
 *   Tax computation is done in floating point and rounded only at the boundary, which
 *   mirrors how IRS worksheets behave. Use {@link roundCents} on anything you display.
 * - Every parameter set is keyed by tax year and carries its own citations, so a
 *   consumer can always trace a number back to the Revenue Procedure it came from.
 */

/** IRS filing status. */
export type FilingStatus =
  | 'single'
  | 'marriedFilingJointly'
  | 'marriedFilingSeparately'
  | 'headOfHousehold'
  | 'qualifyingSurvivingSpouse';

export const FILING_STATUSES: readonly FilingStatus[] = [
  'single',
  'marriedFilingJointly',
  'marriedFilingSeparately',
  'headOfHousehold',
  'qualifyingSurvivingSpouse',
];

/**
 * One marginal rate band.
 *
 * `upTo` is the *upper* bound of taxable income for this band (inclusive in the
 * sense that income at exactly `upTo` is still taxed at `rate`). The final band
 * uses `Infinity`.
 */
export interface Bracket {
  readonly rate: number;
  readonly upTo: number;
}

/** Per-band detail returned alongside a bracket computation. */
export interface BracketDetail {
  readonly rate: number;
  /** Amount of taxable income falling inside this band. */
  readonly incomeInBracket: number;
  /** Tax generated by this band. */
  readonly tax: number;
}

export interface IncomeTaxResult {
  readonly taxableIncome: number;
  readonly tax: number;
  /** Rate applied to the next dollar of ordinary income. */
  readonly marginalRate: number;
  /** `tax / taxableIncome`, or 0 when there is no taxable income. */
  readonly effectiveRate: number;
  readonly brackets: readonly BracketDetail[];
}

export interface SelfEmploymentTaxResult {
  /** Net profit multiplied by {@link YearParameters.seNetEarningsFactor}. */
  readonly netEarnings: number;
  /** 12.4% OASDI portion, capped by the Social Security wage base. */
  readonly socialSecurity: number;
  /** 2.9% Medicare portion, uncapped. */
  readonly medicare: number;
  /** `socialSecurity + medicare` — the Schedule SE total. */
  readonly total: number;
  /**
   * The above-the-line deduction for one half of SE tax.
   *
   * Note this is half of the Schedule SE total only. Additional Medicare Tax
   * (Form 8959) is *not* deductible and is not included here.
   */
  readonly deductibleHalf: number;
  /** True when net earnings fell below the $400 filing floor, so no SE tax is due. */
  readonly belowThreshold: boolean;
}

export interface FicaSide {
  readonly socialSecurity: number;
  readonly medicare: number;
  readonly total: number;
}

export interface FicaResult {
  readonly employee: FicaSide & { readonly additionalMedicare: number };
  /** Employers match OASDI and Medicare but never pay Additional Medicare Tax. */
  readonly employer: FicaSide;
}

export interface CapitalGainsResult {
  readonly tax: number;
  readonly brackets: readonly BracketDetail[];
}

/** A citation for a parameter set, so numbers are always traceable. */
export interface Citation {
  readonly title: string;
  readonly url: string;
}

export interface YearParameters {
  readonly year: number;
  readonly ordinaryBrackets: Readonly<Record<FilingStatus, readonly Bracket[]>>;
  readonly standardDeduction: Readonly<Record<FilingStatus, number>>;
  /** Extra standard deduction *per qualifying condition* (age 65+, blind). */
  readonly additionalStandardDeduction: Readonly<Record<FilingStatus, number>>;
  readonly socialSecurityWageBase: number;
  readonly rates: {
    readonly socialSecurityEmployee: number;
    readonly socialSecurityEmployer: number;
    readonly medicareEmployee: number;
    readonly medicareEmployer: number;
    readonly additionalMedicare: number;
    readonly seSocialSecurity: number;
    readonly seMedicare: number;
  };
  readonly additionalMedicareThreshold: Readonly<Record<FilingStatus, number>>;
  /** Portion of net profit subject to SE tax (92.35%). */
  readonly seNetEarningsFactor: number;
  /** Net earnings below this produce no SE tax. */
  readonly seMinimumNetEarnings: number;
  readonly longTermCapitalGains: Readonly<Record<FilingStatus, readonly Bracket[]>>;
  readonly niit: {
    readonly rate: number;
    readonly thresholds: Readonly<Record<FilingStatus, number>>;
  };
  readonly sources: readonly Citation[];
}
